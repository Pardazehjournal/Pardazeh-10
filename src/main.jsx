function useTheme() {
  const [dark, setDark] = useState(() => {
    try {
      return localStorage.getItem('pardazeh-theme') !== 'light';
    } catch {
      return true;
    }
  });

  useEffect(() => {
    document.documentElement.dataset.theme = dark ? 'dark' : 'light';

    document.documentElement.style.setProperty(
      '--logo-filter',
      dark ? 'brightness(0) invert(1)' : 'brightness(0) saturate(100%)'
    );

    document.documentElement.style.setProperty(
      '--light-page-bg',
      dark ? '#0b1015' : '#e8e4da'
    );

    document.documentElement.style.setProperty(
      '--light-surface',
      dark ? '#0d191c' : '#eeebe2'
    );

    document.documentElement.style.setProperty(
      '--light-border',
      dark ? 'rgba(255,255,255,.08)' : 'rgba(31,45,43,.13)'
    );

    try {
      localStorage.setItem(
        'pardazeh-theme',
        dark ? 'dark' : 'light'
      );
    } catch {}
  }, [dark]);

  return [dark, setDark];
}

