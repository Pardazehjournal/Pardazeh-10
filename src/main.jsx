function ArticlePage({ article }) {
  const idx = articles.findIndex(
    (x) => x.id === article.id
  );

  const prev =
    articles[
      (idx - 1 + articles.length) %
        articles.length
    ];

  const next =
    articles[
      (idx + 1) % articles.length
    ];

  useEffect(() => {
    window.scrollTo(0, 0);

    const onScroll = () => {
      const h = document.documentElement;

      const max =
        h.scrollHeight - window.innerHeight;

      const p =
        max > 0
          ? Math.min(
              100,
              (window.scrollY / max) * 100
            )
          : 0;

      document.documentElement.style.setProperty(
        '--read-progress',
        `${p}%`
      );
    };

    onScroll();

    window.addEventListener(
      'scroll',
      onScroll,
      { passive: true }
    );

    return () =>
      window.removeEventListener(
        'scroll',
        onScroll
      );
  }, [article.id]);

  if (article.id === 'mind') {
    return (
      <MindArticle
        article={article}
        prev={prev}
        next={next}
      />
    );
  }

  return (
    <SourceArticle
      article={article}
      info={sourceArticles[article.id]}
      prev={prev}
      next={next}
    />
  );
}

