function BinaryField() {
  const bits = useMemo(
    () =>
      Array.from(
        { length: 135 },
        (_, i) => ({
          v: i % 3 ? '0' : '1',
          x: (i * 11.7) % 100,
          y: (i * 17.3) % 100,
          d: (i % 9) * -0.7
        })
      ),
    []
  );

  return (
    <div className="bits">
      {bits.map((b, i) => (
        <span
          key={i}
          style={{
            left: `${b.x}%`,
            top: `${b.y}%`,
            animationDelay: `${b.d}s`
          }}
        >
          {b.v}
        </span>
      ))}
    </div>
  );
}

function Cover() {
  const ref = useRef();
  const [flipped, setFlipped] = useState(false);

  const move = (e) => {
    const r =
      ref.current?.getBoundingClientRect();

    if (!r) return;

    const x =
      (e.clientX - r.left) / r.width - 0.5;

    const y =
      (e.clientY - r.top) / r.height - 0.5;

    ref.current.style.setProperty(
      '--rx',
      `${-y * 6}deg`
    );

    if (!flipped) {
      ref.current.style.setProperty(
        '--ry',
        `${x * 8}deg`
      );
    }
  };

  const leave = () => {
    ref.current?.style.setProperty(
      '--rx',
      '0deg'
    );

    ref.current?.style.setProperty(
      '--ry',
      '0deg'
    );
  };

  return (
    <div
      className="cover-wrap"
      onMouseMove={move}
      onMouseLeave={leave}
    >
      <div className="cover-ring r1" />
      <div className="cover-ring r2" />
      <div className="cover-shadow" />

      <button
        type="button"
        className={`cover-flip ${
          flipped ? 'is-flipped' : ''
        }`}
        onClick={() => setFlipped((v) => !v)}
        aria-label={
          flipped
            ? 'نمایش جلد اصلی'
            : 'نمایش جلد پشتی'
        }
      >
        <div ref={ref} className="cover">
          <div className="cover-face cover-front">
            <img
              src={A + 'cover.jpg'}
              alt="جلد شماره دهم پردازه"
            />
            <i />
          </div>

          <div className="cover-face cover-back">
            <img
              src={A + 'back-cover.jpg'}
              alt="جلد پشتی شماره دهم پردازه"
            />
          </div>
        </div>
      </button>
    </div>
  );
}

function Reveal({
  children,
  className = ''
}) {
  const [show, setShow] = useState(false);
  const ref = useRef();

  useEffect(() => {
    const o = new IntersectionObserver(
      ([e]) => {
        if (e.isIntersecting) {
          setShow(true);
          o.disconnect();
        }
      },
      { threshold: 0.12 }
    );

    if (ref.current) {
      o.observe(ref.current);
    }

    return () => o.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={`reveal ${
        show ? 'show' : ''
      } ${className}`}
    >
      {children}
    </div>
  );
}

